def _junctions():
    """위 덩어리와 갈비 A(x 6.857)·B(x 9.429) 만나는 오목 모서리 (x,z) — y 27 기준"""
    (x1, z1), (x2, z2) = UP; r = 1.889
    L = math.hypot(x2 - x1, z2 - z1); t = ((x2 - x1) / L, (z2 - z1) / L); n = (-t[1], t[0])
    pts = []
    for xe in (6.857, 9.429):
        for sg in (1, -1):
            a = (x1 + sg * r * n[0], z1 + sg * r * n[1]); s_ = (xe - a[0]) / t[0]
            if 0 <= s_ <= L:
                pts.append((xe, a[1] + s_ * t[1]))
        for (cx, cz) in UP:
            dx = xe - cx
            if abs(dx) < r:
                for sg in (1, -1):
                    zz = cz + sg * math.sqrt(r * r - dx * dx)
                    # 원의 바깥 경계에 있는 점만 (다른 원·접선 안쪽이면 제외)
                    pts.append((xe, zz))
    return pts
JUNC = _junctions()


def _on_junction(a, b):
    if abs(abs(a[1] - b[1]) - 2.0) > 0.05 or min(a[1], b[1]) < 26.9:
        return False
    for (jx, jz) in JUNC:
        for sx in (1, -1):
            if all(abs(p[0] - sx * jx) < 0.1 and abs(p[2] - jz) < 0.1 for p in (a, b)):
                return True
    return False


